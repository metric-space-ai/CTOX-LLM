use std::fs;
use std::path::PathBuf;
use std::time::Instant;

use anyhow::Context;
use clap::Parser;
use ctox_qwen38_27b::backend::cpu::CpuBackend;
use ctox_qwen38_27b::backend::cuda_runtime::CudaCandidateRuntime;
use ctox_qwen38_27b::backend::{Activation, Backend, FusedMatVec, ScaleSlice};
use ctox_qwen38_27b::format::TensorDType;
use ctox_qwen38_27b::quant::{A8Block64, Q2Block64, Q4Block64, BLOCK_LEN};
use half::f16;
use serde::Serialize;
use sha2::{Digest, Sha256};

#[derive(Debug, Parser)]
#[command(about = "Verify one shared corrected A8 Q/K/V CUDA fan-out")]
struct Args {
    /// Cubin generated by scripts/build_cuda_sm86.sh.
    #[arg(long)]
    module: PathBuf,
    #[arg(long, default_value_t = 0)]
    device: i32,
    #[arg(long, default_value_t = 5_120)]
    columns: usize,
    #[arg(long, default_value_t = 5)]
    warmup: usize,
    #[arg(long, default_value_t = 20)]
    iterations: usize,
    #[arg(long, default_value_t = 10)]
    dispatches_per_sync: usize,
    #[arg(long, default_value_t = 2.0e-2)]
    absolute_tolerance: f32,
    #[arg(long, default_value_t = 1.0e-3)]
    relative_tolerance: f32,
}

struct ProjectionFixture {
    name: &'static str,
    dtype: TensorDType,
    rows: usize,
    weights: Vec<u8>,
    s_out: Vec<u8>,
    bias: Vec<f32>,
}

impl ProjectionFixture {
    fn operation<'a>(&'a self, input: &'a [f32], s_in: &'a [u8]) -> FusedMatVec<'a> {
        FusedMatVec {
            dtype: self.dtype,
            weights: &self.weights,
            segments: &[],
            rows: self.rows,
            columns: input.len(),
            input,
            s_in: Some(ScaleSlice::F16Le(s_in)),
            s_out: Some(ScaleSlice::F16Le(&self.s_out)),
            bias: Some(&self.bias),
            activation: Activation::Identity,
        }
    }
}

#[derive(Serialize)]
struct ProjectionReport {
    name: &'static str,
    dtype: &'static str,
    rows: usize,
    packed_weight_bytes: usize,
    maximum_absolute_error: f32,
    maximum_relative_error: f32,
    maximum_a8_quality_delta_vs_exact: f32,
}

#[derive(Serialize)]
struct Report<'a> {
    format: &'static str,
    status: &'static str,
    device: &'a str,
    compute_capability: String,
    module_path: String,
    module_sha256: String,
    columns: usize,
    fanout_projections: usize,
    quantizations_per_fanout_pass: usize,
    warmup: usize,
    iterations: usize,
    dispatches_per_sync: usize,
    total_projection_dispatches: usize,
    packed_weight_bytes_per_fanout: usize,
    isolated_requested_resident_bytes: usize,
    shared_requested_resident_bytes: usize,
    requested_resident_bytes_saved: usize,
    verifier_device_input_bytes: usize,
    device_view_path_verified: bool,
    mismatched_s_in_rejected: bool,
    elapsed_milliseconds: f64,
    mean_fanout_pass_milliseconds: f64,
    packed_weight_gb_per_second: f64,
    projections: Vec<ProjectionReport>,
    absolute_tolerance: f32,
    relative_tolerance: f32,
    note: &'static str,
}

fn main() -> anyhow::Result<()> {
    let args = Args::parse();
    anyhow::ensure!(
        args.columns > 0 && args.columns.is_multiple_of(BLOCK_LEN),
        "columns must be a positive multiple of {BLOCK_LEN}"
    );
    anyhow::ensure!(args.iterations > 0, "iterations must be positive");
    anyhow::ensure!(
        args.dispatches_per_sync > 0,
        "dispatches-per-sync must be positive"
    );
    let module = fs::read(&args.module)
        .with_context(|| format!("failed to read CUDA module {}", args.module.display()))?;
    let module_sha256 = format!("{:x}", Sha256::digest(&module));
    let input: Vec<f32> = (0..args.columns)
        .map(|index| (index as f32 * 0.031_25).cos())
        .collect();
    let s_in = f16_bytes(
        &(0..args.columns)
            .map(|index| 0.9 + 0.001 * (index % 11) as f32)
            .collect::<Vec<_>>(),
    );
    let fixtures = [
        fixture("q_proj", TensorDType::Q4B64, 12_288, args.columns, 11)?,
        fixture("k_proj", TensorDType::Q2B64, 1_024, args.columns, 23)?,
        fixture("v_proj", TensorDType::Q2B64, 1_024, args.columns, 37)?,
    ];
    let operations: Vec<_> = fixtures
        .iter()
        .map(|fixture| fixture.operation(&input, &s_in))
        .collect();
    let exact_oracles: Vec<_> = operations
        .iter()
        .map(|operation| CpuBackend::scalar_verifier().fused_matvec(operation))
        .collect::<Result<_, _>>()?;
    let a8_oracles: Vec<_> = operations
        .iter()
        .map(a8_execution_oracle)
        .collect::<Result<_, _>>()?;

    let runtime = CudaCandidateRuntime::new(&module, args.device)?;
    let isolated_requested_resident_bytes = operations
        .iter()
        .map(|operation| runtime.prepare_a8_fused_matvec(operation))
        .collect::<Result<Vec<_>, _>>()?
        .iter()
        .map(|prepared| prepared.resident_bytes())
        .sum();

    let shared_activation = runtime.prepare_shared_a8_activation(&operations[0])?;
    let shared_projections = operations
        .iter()
        .map(|operation| runtime.prepare_shared_a8_projection(operation))
        .collect::<Result<Vec<_>, _>>()?;
    let projection_refs: Vec<_> = shared_projections.iter().collect();
    let shared_requested_resident_bytes = shared_activation.resident_bytes()
        + shared_projections
            .iter()
            .map(|projection| projection.resident_bytes())
            .sum::<usize>();
    let verifier_device_input = runtime.prepare_verifier_f32_tensor(&input)?;
    let cuda_output_views = runtime.dispatch_shared_a8_fanout_device(
        &shared_activation,
        verifier_device_input.device_view()?,
        &projection_refs,
    )?;
    let cuda_outputs = cuda_output_views
        .into_iter()
        .map(|output| runtime.verifier_read_f32(output))
        .collect::<Result<Vec<_>, _>>()?;

    let projections = fixtures
        .iter()
        .zip(
            exact_oracles
                .iter()
                .zip(a8_oracles.iter().zip(&cuda_outputs)),
        )
        .map(|(fixture, (exact, (a8, cuda)))| {
            let (maximum_absolute_error, maximum_relative_error) =
                compare(a8, cuda, args.absolute_tolerance, args.relative_tolerance)?;
            Ok(ProjectionReport {
                name: fixture.name,
                dtype: dtype_name(fixture.dtype),
                rows: fixture.rows,
                packed_weight_bytes: fixture.weights.len(),
                maximum_absolute_error,
                maximum_relative_error,
                maximum_a8_quality_delta_vs_exact: exact
                    .iter()
                    .zip(a8)
                    .map(|(left, right)| (left - right).abs())
                    .fold(0.0_f32, f32::max),
            })
        })
        .collect::<anyhow::Result<Vec<_>>>()?;

    let mut mismatched_s_in = s_in.clone();
    mismatched_s_in[..2].copy_from_slice(&f16::from_f32(1.25).to_bits().to_le_bytes());
    let mismatched_operation = fixtures[0].operation(&input, &mismatched_s_in);
    let mismatched_projection = runtime.prepare_shared_a8_projection(&mismatched_operation)?;
    let mismatched_s_in_rejected = runtime
        .dispatch_shared_a8_fanout_device(
            &shared_activation,
            verifier_device_input.device_view()?,
            &[&mismatched_projection],
        )
        .is_err();
    anyhow::ensure!(
        mismatched_s_in_rejected,
        "shared fan-out accepted different s_in bytes"
    );
    drop(mismatched_projection);

    for _ in 0..args.warmup {
        runtime.quantize_shared_a8_activation(&shared_activation)?;
        std::hint::black_box(runtime.dispatch_prepared_shared_a8_fanout_repeated(
            &shared_activation,
            &projection_refs,
            args.dispatches_per_sync,
        )?);
    }
    let started = Instant::now();
    for _ in 0..args.iterations {
        runtime.quantize_shared_a8_activation(&shared_activation)?;
        std::hint::black_box(runtime.dispatch_prepared_shared_a8_fanout_repeated(
            &shared_activation,
            &projection_refs,
            args.dispatches_per_sync,
        )?);
    }
    let elapsed = started.elapsed().as_secs_f64();
    let packed_weight_bytes_per_fanout = fixtures
        .iter()
        .map(|fixture| fixture.weights.len())
        .sum::<usize>();
    let total_fanout_passes = args.iterations * args.dispatches_per_sync;
    let total_projection_dispatches = total_fanout_passes * fixtures.len();
    let (major, minor) = runtime.compute_capability();
    println!(
        "{}",
        serde_json::to_string_pretty(&Report {
            format: "ctox.cuda-sm86-shared-a8-fanout-benchmark.v2",
            status: "verifier_only_not_promotion_evidence",
            device: runtime.device_name(),
            compute_capability: format!("{major}.{minor}"),
            module_path: args.module.display().to_string(),
            module_sha256,
            columns: args.columns,
            fanout_projections: fixtures.len(),
            quantizations_per_fanout_pass: 1,
            warmup: args.warmup,
            iterations: args.iterations,
            dispatches_per_sync: args.dispatches_per_sync,
            total_projection_dispatches,
            packed_weight_bytes_per_fanout,
            isolated_requested_resident_bytes,
            shared_requested_resident_bytes,
            requested_resident_bytes_saved: isolated_requested_resident_bytes
                .saturating_sub(shared_requested_resident_bytes),
            verifier_device_input_bytes: verifier_device_input.resident_bytes(),
            device_view_path_verified: true,
            mismatched_s_in_rejected,
            elapsed_milliseconds: elapsed * 1_000.0,
            mean_fanout_pass_milliseconds: elapsed * 1_000.0 / total_fanout_passes as f64,
            packed_weight_gb_per_second: packed_weight_bytes_per_fanout as f64
                * total_fanout_passes as f64
                / elapsed
                / 1.0e9,
            projections,
            absolute_tolerance: args.absolute_tolerance,
            relative_tolerance: args.relative_tolerance,
            note: "One packed-FP16 s_in identity and one transient A8 buffer feed Q4 Q plus Q2 K/V. Numerical verification feeds that fan-out through a producer-owned CUDA device view and reads outputs only through the explicit verifier API. Timed intervals retain the resident verifier input and include output copies plus host dispatch; packed-byte GB/s is not hardware-counter roofline evidence.",
        })?
    );
    Ok(())
}

fn fixture(
    name: &'static str,
    dtype: TensorDType,
    rows: usize,
    columns: usize,
    phase: usize,
) -> anyhow::Result<ProjectionFixture> {
    let weights = packed_weights(dtype, rows, columns, phase)?;
    let s_out = f16_bytes(
        &(0..rows)
            .map(|row| 1.1 - 0.002 * (row % 9) as f32)
            .collect::<Vec<_>>(),
    );
    let bias = (0..rows)
        .map(|row| ((row + phase) as f32 * 0.77).sin() * 0.05)
        .collect();
    Ok(ProjectionFixture {
        name,
        dtype,
        rows,
        weights,
        s_out,
        bias,
    })
}

fn packed_weights(
    dtype: TensorDType,
    rows: usize,
    columns: usize,
    phase_offset: usize,
) -> anyhow::Result<Vec<u8>> {
    let block_count = rows
        .checked_mul(columns / BLOCK_LEN)
        .ok_or_else(|| anyhow::anyhow!("matrix block count overflows"))?;
    let block_bytes = match dtype {
        TensorDType::Q2B64 => 18,
        TensorDType::Q4B64 => 34,
        _ => anyhow::bail!("fan-out fixture supports only Q2/Q4"),
    };
    let mut weights = Vec::with_capacity(block_count * block_bytes);
    for matrix_block in 0..block_count {
        let values: [f32; BLOCK_LEN] = std::array::from_fn(|index| {
            let phase = (phase_offset + matrix_block * BLOCK_LEN + index) as f32;
            (phase * 0.013_579).sin() * 0.25
        });
        match dtype {
            TensorDType::Q2B64 => {
                weights.extend_from_slice(&Q2Block64::quantize(&values)?.encode())
            }
            TensorDType::Q4B64 => {
                weights.extend_from_slice(&Q4Block64::quantize(&values)?.encode())
            }
            _ => unreachable!(),
        }
    }
    Ok(weights)
}

fn a8_execution_oracle(operation: &FusedMatVec<'_>) -> anyhow::Result<Vec<f32>> {
    let mut corrected = Vec::with_capacity(operation.columns);
    for (index, value) in operation.input.iter().enumerate() {
        corrected.push(
            *value
                * operation
                    .s_in
                    .map(|scales| scales.value(index))
                    .transpose()?
                    .unwrap_or(1.0),
        );
    }
    let mut dequantized = Vec::with_capacity(operation.columns);
    for block in corrected.chunks_exact(BLOCK_LEN) {
        dequantized.extend_from_slice(&A8Block64::quantize(block)?.dequantize());
    }
    Ok(CpuBackend::scalar_verifier().fused_matvec(&FusedMatVec {
        input: &dequantized,
        s_in: None,
        ..*operation
    })?)
}

fn compare(
    expected: &[f32],
    actual: &[f32],
    absolute_tolerance: f32,
    relative_tolerance: f32,
) -> anyhow::Result<(f32, f32)> {
    anyhow::ensure!(expected.len() == actual.len(), "CUDA output length differs");
    let mut maximum_absolute_error = 0.0_f32;
    let mut maximum_relative_error = 0.0_f32;
    for (expected, actual) in expected.iter().zip(actual) {
        let absolute = (expected - actual).abs();
        maximum_absolute_error = maximum_absolute_error.max(absolute);
        maximum_relative_error =
            maximum_relative_error.max(absolute / expected.abs().max(f32::MIN_POSITIVE));
        anyhow::ensure!(
            absolute <= absolute_tolerance + relative_tolerance * expected.abs(),
            "CUDA result {actual} differs from A8 oracle {expected} by {absolute}"
        );
    }
    Ok((maximum_absolute_error, maximum_relative_error))
}

fn f16_bytes(values: &[f32]) -> Vec<u8> {
    values
        .iter()
        .flat_map(|value| f16::from_f32(*value).to_bits().to_le_bytes())
        .collect()
}

fn dtype_name(dtype: TensorDType) -> &'static str {
    match dtype {
        TensorDType::Q2B64 => "q2_b64",
        TensorDType::Q4B64 => "q4_b64",
        _ => unreachable!(),
    }
}
