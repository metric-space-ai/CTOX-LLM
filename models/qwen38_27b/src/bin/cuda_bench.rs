use std::fs;
use std::path::PathBuf;
use std::time::Instant;

use anyhow::Context;
use clap::{Parser, ValueEnum};
use ctox_qwen38_27b::backend::cpu::CpuBackend;
use ctox_qwen38_27b::backend::cuda_runtime::{
    CudaCandidateRuntime, PreparedCudaA8MatVec, PreparedCudaMatVec, PreparedCudaMixedA8MatVec,
};
use ctox_qwen38_27b::backend::{Activation, Backend, FusedMatVec, ScaleSlice};
use ctox_qwen38_27b::format::{QuantSegment, TensorDType};
use ctox_qwen38_27b::quant::{A8Block64, Q2Block64, Q4Block64, BLOCK_LEN};
use half::f16;
use serde::Serialize;
use sha2::{Digest, Sha256};

#[derive(Debug, Clone, Copy, ValueEnum)]
enum DTypeArg {
    Q2,
    Q4,
    Mixed,
}

#[derive(Debug, Clone, Copy, ValueEnum)]
enum ExecutionPathArg {
    Exact,
    A8Dp4a,
}

#[derive(Debug, Parser)]
#[command(about = "Verify and benchmark resident Q2/Q4 CUDA SM86 matvec")]
struct Args {
    /// Cubin generated by scripts/build_cuda_sm86.sh.
    #[arg(long)]
    module: PathBuf,
    #[arg(long, value_enum, default_value_t = DTypeArg::Q2)]
    dtype: DTypeArg,
    #[arg(long, value_enum, default_value_t = ExecutionPathArg::Exact)]
    execution_path: ExecutionPathArg,
    #[arg(long, default_value_t = 0)]
    device: i32,
    #[arg(long, default_value_t = 5_120)]
    rows: usize,
    #[arg(long, default_value_t = 5_120)]
    columns: usize,
    #[arg(long, default_value_t = 5)]
    warmup: usize,
    #[arg(long, default_value_t = 20)]
    iterations: usize,
    #[arg(long, default_value_t = 10)]
    dispatches_per_sync: usize,
    #[arg(long, default_value_t = 2.0e-2)]
    absolute_tolerance: f32,
    #[arg(long, default_value_t = 1.0e-3)]
    relative_tolerance: f32,
}

#[derive(Serialize)]
struct Report<'a> {
    format: &'static str,
    status: &'static str,
    device: &'a str,
    compute_capability: String,
    module_path: String,
    module_sha256: String,
    dtype: &'static str,
    execution_path: &'static str,
    rows: usize,
    columns: usize,
    warmup: usize,
    iterations: usize,
    dispatches_per_sync: usize,
    quantizations_per_sync: usize,
    total_dispatches: usize,
    packed_weight_bytes: usize,
    requested_resident_buffer_bytes: usize,
    elapsed_milliseconds: f64,
    mean_dispatch_milliseconds: f64,
    dispatches_per_second: f64,
    packed_weight_gb_per_second: f64,
    maximum_absolute_error: f32,
    maximum_relative_error: f32,
    maximum_a8_quality_delta_vs_exact: f32,
    absolute_tolerance: f32,
    relative_tolerance: f32,
    note: &'static str,
}

enum Prepared {
    Exact(PreparedCudaMatVec),
    A8(PreparedCudaA8MatVec),
    MixedA8(PreparedCudaMixedA8MatVec),
}

impl Prepared {
    fn resident_bytes(&self) -> usize {
        match self {
            Self::Exact(prepared) => prepared.resident_bytes(),
            Self::A8(prepared) => prepared.resident_bytes(),
            Self::MixedA8(prepared) => prepared.resident_bytes(),
        }
    }
}

fn main() -> anyhow::Result<()> {
    let args = Args::parse();
    anyhow::ensure!(args.rows > 0, "rows must be positive");
    anyhow::ensure!(
        args.columns > 0 && args.columns.is_multiple_of(BLOCK_LEN),
        "columns must be a positive multiple of {BLOCK_LEN}"
    );
    anyhow::ensure!(args.iterations > 0, "iterations must be positive");
    anyhow::ensure!(
        args.dispatches_per_sync > 0,
        "dispatches-per-sync must be positive"
    );
    anyhow::ensure!(
        args.absolute_tolerance >= 0.0 && args.relative_tolerance >= 0.0,
        "tolerances must be non-negative"
    );
    let module = fs::read(&args.module)
        .with_context(|| format!("failed to read CUDA module {}", args.module.display()))?;
    let module_sha256 = format!("{:x}", Sha256::digest(&module));
    let dtype = match args.dtype {
        DTypeArg::Q2 => TensorDType::Q2B64,
        DTypeArg::Q4 => TensorDType::Q4B64,
        DTypeArg::Mixed => TensorDType::MixedQ2Q4B64,
    };
    anyhow::ensure!(
        !matches!(args.dtype, DTypeArg::Mixed) || args.rows >= 2,
        "mixed benchmark requires at least two rows"
    );
    anyhow::ensure!(
        !matches!(args.dtype, DTypeArg::Mixed)
            || matches!(args.execution_path, ExecutionPathArg::A8Dp4a),
        "mixed benchmark currently requires --execution-path a8-dp4a"
    );
    let (weights, segments) = packed_weights_and_segments(dtype, args.rows, args.columns)?;
    let input: Vec<f32> = (0..args.columns)
        .map(|index| (index as f32 * 0.031_25).cos())
        .collect();
    let s_in = f16_bytes(
        &(0..args.columns)
            .map(|index| 0.9 + 0.001 * (index % 11) as f32)
            .collect::<Vec<_>>(),
    );
    let s_out = f16_bytes(
        &(0..args.rows)
            .map(|row| 1.1 - 0.002 * (row % 9) as f32)
            .collect::<Vec<_>>(),
    );
    let bias: Vec<f32> = (0..args.rows)
        .map(|row| (row as f32 * 0.77).sin() * 0.05)
        .collect();
    let operation = FusedMatVec {
        dtype,
        weights: &weights,
        segments: &segments,
        rows: args.rows,
        columns: args.columns,
        input: &input,
        s_in: Some(ScaleSlice::F16Le(&s_in)),
        s_out: Some(ScaleSlice::F16Le(&s_out)),
        bias: Some(&bias),
        activation: Activation::Silu,
    };

    let scalar_output = CpuBackend::scalar_verifier().fused_matvec(&operation)?;
    let execution_oracle = match args.execution_path {
        ExecutionPathArg::Exact => scalar_output.clone(),
        ExecutionPathArg::A8Dp4a => a8_execution_oracle(&operation)?,
    };
    let runtime = CudaCandidateRuntime::new(&module, args.device)?;
    let prepared = match args.execution_path {
        ExecutionPathArg::Exact => Prepared::Exact(runtime.prepare_fused_matvec(&operation)?),
        ExecutionPathArg::A8Dp4a if dtype == TensorDType::MixedQ2Q4B64 => {
            Prepared::MixedA8(runtime.prepare_mixed_a8_fused_matvec(&operation)?)
        }
        ExecutionPathArg::A8Dp4a => Prepared::A8(runtime.prepare_a8_fused_matvec(&operation)?),
    };
    let cuda_output = match &prepared {
        Prepared::Exact(prepared) => runtime.dispatch_prepared(prepared)?,
        Prepared::A8(prepared) => runtime.dispatch_a8_fused_matvec(prepared)?,
        Prepared::MixedA8(prepared) => runtime.dispatch_mixed_a8_fused_matvec(prepared)?,
    };
    let mut maximum_absolute_error = 0.0_f32;
    let mut maximum_relative_error = 0.0_f32;
    for (expected, actual) in execution_oracle.iter().zip(&cuda_output) {
        let absolute = (expected - actual).abs();
        let relative = absolute / expected.abs().max(f32::MIN_POSITIVE);
        maximum_absolute_error = maximum_absolute_error.max(absolute);
        maximum_relative_error = maximum_relative_error.max(relative);
        anyhow::ensure!(
            absolute <= args.absolute_tolerance + args.relative_tolerance * expected.abs(),
            "CUDA result {actual} differs from scalar {expected} by {absolute}"
        );
    }
    let maximum_a8_quality_delta_vs_exact = scalar_output
        .iter()
        .zip(&execution_oracle)
        .map(|(exact, a8)| (exact - a8).abs())
        .fold(0.0_f32, f32::max);

    for _ in 0..args.warmup {
        match &prepared {
            Prepared::Exact(prepared) => std::hint::black_box(
                runtime.dispatch_prepared_repeated(prepared, args.dispatches_per_sync)?,
            ),
            Prepared::A8(prepared) => {
                runtime.quantize_prepared_a8(prepared)?;
                std::hint::black_box(
                    runtime.dispatch_prepared_a8_repeated(prepared, args.dispatches_per_sync)?,
                )
            }
            Prepared::MixedA8(prepared) => {
                runtime.quantize_prepared_mixed_a8(prepared)?;
                std::hint::black_box(
                    runtime
                        .dispatch_prepared_mixed_a8_repeated(prepared, args.dispatches_per_sync)?,
                )
            }
        };
    }
    let started = Instant::now();
    for _ in 0..args.iterations {
        match &prepared {
            Prepared::Exact(prepared) => std::hint::black_box(
                runtime.dispatch_prepared_repeated(prepared, args.dispatches_per_sync)?,
            ),
            Prepared::A8(prepared) => {
                runtime.quantize_prepared_a8(prepared)?;
                std::hint::black_box(
                    runtime.dispatch_prepared_a8_repeated(prepared, args.dispatches_per_sync)?,
                )
            }
            Prepared::MixedA8(prepared) => {
                runtime.quantize_prepared_mixed_a8(prepared)?;
                std::hint::black_box(
                    runtime
                        .dispatch_prepared_mixed_a8_repeated(prepared, args.dispatches_per_sync)?,
                )
            }
        };
    }
    let elapsed = started.elapsed().as_secs_f64();
    let total_dispatches = args
        .iterations
        .checked_mul(args.dispatches_per_sync)
        .ok_or_else(|| anyhow::anyhow!("total dispatch count overflows"))?;
    let mean_seconds = elapsed / total_dispatches as f64;
    let (major, minor) = runtime.compute_capability();
    println!(
        "{}",
        serde_json::to_string_pretty(&Report {
            format: "ctox.cuda-sm86-candidate-benchmark.v1",
            status: "verifier_only_not_promotion_evidence",
            device: runtime.device_name(),
            compute_capability: format!("{major}.{minor}"),
            module_path: args.module.display().to_string(),
            module_sha256,
            dtype: match dtype {
                TensorDType::Q2B64 => "q2_b64",
                TensorDType::Q4B64 => "q4_b64",
                TensorDType::MixedQ2Q4B64 => "mixed_q2_q4_b64",
                _ => unreachable!(),
            },
            execution_path: match args.execution_path {
                ExecutionPathArg::Exact => "exact_f32_activation",
                ExecutionPathArg::A8Dp4a => "symmetric_a8_b64_dp4a",
            },
            rows: args.rows,
            columns: args.columns,
            warmup: args.warmup,
            iterations: args.iterations,
            dispatches_per_sync: args.dispatches_per_sync,
            quantizations_per_sync: usize::from(matches!(
                args.execution_path,
                ExecutionPathArg::A8Dp4a
            )),
            total_dispatches,
            packed_weight_bytes: weights.len(),
            requested_resident_buffer_bytes: prepared.resident_bytes(),
            elapsed_milliseconds: elapsed * 1_000.0,
            mean_dispatch_milliseconds: mean_seconds * 1_000.0,
            dispatches_per_second: mean_seconds.recip(),
            packed_weight_gb_per_second: weights.len() as f64 / mean_seconds / 1.0e9,
            maximum_absolute_error,
            maximum_relative_error,
            maximum_a8_quality_delta_vs_exact,
            absolute_tolerance: args.absolute_tolerance,
            relative_tolerance: args.relative_tolerance,
            note: "Synchronous resident verifier interval. The A8 path includes one activation quantization per sync and amortizes it across dispatches-per-sync. Requested bytes exclude CUDA allocator/context overhead; packed-weight GB/s is not yet a hardware-counter roofline measurement.",
        })?
    );
    Ok(())
}

fn a8_execution_oracle(operation: &FusedMatVec<'_>) -> anyhow::Result<Vec<f32>> {
    let mut corrected = Vec::with_capacity(operation.columns);
    for (index, value) in operation.input.iter().enumerate() {
        corrected.push(
            *value
                * operation
                    .s_in
                    .map(|scales| scales.value(index))
                    .transpose()?
                    .unwrap_or(1.0),
        );
    }
    let mut dequantized = Vec::with_capacity(operation.columns);
    for block in corrected.chunks_exact(BLOCK_LEN) {
        dequantized.extend_from_slice(&A8Block64::quantize(block)?.dequantize());
    }
    let a8_operation = FusedMatVec {
        dtype: operation.dtype,
        weights: operation.weights,
        segments: operation.segments,
        rows: operation.rows,
        columns: operation.columns,
        input: &dequantized,
        s_in: None,
        s_out: operation.s_out,
        bias: operation.bias,
        activation: operation.activation,
    };
    Ok(CpuBackend::scalar_verifier().fused_matvec(&a8_operation)?)
}

fn packed_weights(dtype: TensorDType, rows: usize, columns: usize) -> anyhow::Result<Vec<u8>> {
    let block_count = rows
        .checked_mul(columns / BLOCK_LEN)
        .ok_or_else(|| anyhow::anyhow!("matrix block count overflows"))?;
    let block_bytes = match dtype {
        TensorDType::Q2B64 => 18,
        TensorDType::Q4B64 => 34,
        _ => unreachable!(),
    };
    let mut weights = Vec::with_capacity(
        block_count
            .checked_mul(block_bytes)
            .ok_or_else(|| anyhow::anyhow!("packed matrix size overflows"))?,
    );
    for matrix_block in 0..block_count {
        let values: [f32; BLOCK_LEN] = std::array::from_fn(|index| {
            let phase = (matrix_block * BLOCK_LEN + index) as f32;
            (phase * 0.013_579).sin() * 0.25
        });
        match dtype {
            TensorDType::Q2B64 => {
                weights.extend_from_slice(&Q2Block64::quantize(&values)?.encode())
            }
            TensorDType::Q4B64 => {
                weights.extend_from_slice(&Q4Block64::quantize(&values)?.encode())
            }
            _ => unreachable!(),
        }
    }
    Ok(weights)
}

fn packed_weights_and_segments(
    dtype: TensorDType,
    rows: usize,
    columns: usize,
) -> anyhow::Result<(Vec<u8>, Vec<QuantSegment>)> {
    if dtype != TensorDType::MixedQ2Q4B64 {
        return Ok((packed_weights(dtype, rows, columns)?, Vec::new()));
    }
    let q2_rows = rows.div_ceil(2);
    let q4_rows = rows - q2_rows;
    let q2 = packed_weights(TensorDType::Q2B64, q2_rows, columns)?;
    let q4 = packed_weights(TensorDType::Q4B64, q4_rows, columns)?;
    let mut weights = Vec::with_capacity(q2.len() + q4.len());
    weights.extend_from_slice(&q2);
    weights.extend_from_slice(&q4);
    let segments = vec![
        QuantSegment {
            group_index: 0,
            row_start: 0,
            row_end: q2_rows as u64,
            dtype: TensorDType::Q2B64,
            offset: 0,
            length: q2.len() as u64,
        },
        QuantSegment {
            group_index: 1,
            row_start: q2_rows as u64,
            row_end: rows as u64,
            dtype: TensorDType::Q4B64,
            offset: q2.len() as u64,
            length: q4.len() as u64,
        },
    ];
    Ok((weights, segments))
}

fn f16_bytes(values: &[f32]) -> Vec<u8> {
    values
        .iter()
        .flat_map(|value| f16::from_f32(*value).to_bits().to_le_bytes())
        .collect()
}
